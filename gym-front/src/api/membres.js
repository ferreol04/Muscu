export const deleteMembre      = (id)     => api.delete(`/membres/${id}`)
export const renouvelerAbonnement = (id, data) => api.post(`/membres/${id}/renouveler`, data)
export const getMembresExpirant = ()      => api.get('/membres-expirant')
export const getCoachs         = (params)     => api.get('/coachs', { params })
